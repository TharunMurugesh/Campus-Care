#!/usr/bin/env bash
# =====================================================================
# CampusCare — one-time database bootstrap
# =====================================================================
# Run with:   sudo bash setup_db.sh
#
# What this does:
#   1. Creates a dedicated DB role `campus_app` (NOT the postgres superuser).
#   2. Creates the database `campus_issue_system` owned by that role.
#   3. Loads schema.sql (scaled, partitioned schema).
#   4. Seeds a global superadmin (you are prompted for email + password;
#      the password is hashed with scrypt before it ever touches disk, and
#      it is NEVER echoed or logged).
#
# Idempotent: re-running drops & recreates the role + database after a
# confirmation prompt. Your sudo password and DB passwords never leave
# this terminal.
# =====================================================================

set -euo pipefail

DB_NAME="${DB_NAME:-campus_issue_system}"
DB_USER="${DB_USER:-campus_app}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# --- colors ----------------------------------------------------------------
green() { printf '\033[1;32m%s\033[0m\n' "$*"; }
yellow() { printf '\033[1;33m%s\033[0m\n' "$*"; }
red()   { printf '\033[1;31m%s\033[0m\n' "$*"; }

# --- sanity checks ---------------------------------------------------------
if [[ "$(id -u)" -ne 0 ]]; then
  red "This script must be run as root (use: sudo bash setup_db.sh)."
  exit 1
fi

if ! command -v psql >/dev/null 2>&1; then
  red "psql not found. Install PostgreSQL client tools first."
  exit 1
fi

if [[ ! -f "$SCRIPT_DIR/schema.sql" ]]; then
  red "schema.sql not found next to this script ($SCRIPT_DIR)."
  exit 1
fi

if [[ ! -f "$SCRIPT_DIR/seed_superadmin.py" ]]; then
  red "seed_superadmin.py not found next to this script."
  exit 1
fi

green "==> CampusCare database bootstrap"
echo    "    Database : $DB_NAME"
echo    "    Role     : $DB_USER"
echo

# --- confirm destructive reset --------------------------------------------
read -r -p "This will DROP and recreate '$DB_NAME' and role '$DB_USER' if they exist. Continue? [y/N] " ans
case "$ans" in
  y|Y) ;;
  *) yellow "Aborted. No changes made."; exit 0 ;;
esac

# --- generate a strong app-role password (kept only in this script's env) --
APP_PASSWORD="$(head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 24)"
if [[ -z "$APP_PASSWORD" ]]; then
  red "Failed to generate a password from /dev/urandom."
  exit 1
fi

green "==> (1/4) Creating/updating role '$DB_USER'"
sudo -u postgres psql -v ON_ERROR_STOP=1 <<SQL
DO \$\$
BEGIN
   IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '$DB_USER') THEN
      CREATE ROLE $DB_USER LOGIN PASSWORD '$APP_PASSWORD';
   ELSE
      ALTER ROLE $DB_USER LOGIN PASSWORD '$APP_PASSWORD';
   END IF;
END\$\$;
SQL

green "==> (2/4) Dropping and recreating database '$DB_NAME'"
sudo -u postgres dropdb --if-exists "$DB_NAME"
sudo -u postgres createdb -O "$DB_USER" "$DB_NAME"

green "==> (3/4) Loading schema.sql"
sudo -u postgres psql -v ON_ERROR_STOP=1 -d "$DB_NAME" -f "$SCRIPT_DIR/schema.sql"

green "==> (4/4) Seeding superadmin"
# The Python seeder hashes the password with Werkzeug scrypt and writes
# only the hash to the DB. We pass secrets via env vars, not argv.
PYTHON_BIN=python3
if ! command -v "$PYTHON_BIN" >/dev/null 2>&1; then
  PYTHON_BIN=python
fi
# Prefer the project venv if present, so Werkzeug is available.
if [[ -x "$SCRIPT_DIR/venv/bin/python" ]]; then
  PYTHON_BIN="$SCRIPT_DIR/venv/bin/python"
fi

sudo -u postgres env PYTHONPATH="$SCRIPT_DIR" "$PYTHON_BIN" "$SCRIPT_DIR/seed_superadmin.py" "$DB_NAME"

# --- write the .env with the freshly generated app password ---------------
ENV_FILE="$SCRIPT_DIR/.env"
SECRET_KEY="$(head -c 32 /dev/urandom | xxd -p -c 64)"
if [[ -z "$SECRET_KEY" ]]; then
  SECRET_KEY="$(date +%s | sha256sum | head -c 64)"
fi

cat > "$ENV_FILE" <<EOF
# Auto-generated by setup_db.sh on $(date -u +%FT%TZ)
DB_HOST=localhost
DB_PORT=5432
DB_NAME=$DB_NAME
DB_USER=$DB_USER
DB_PASSWORD=$APP_PASSWORD
FLASK_SECRET_KEY=$SECRET_KEY
FLASK_ENV=dev
DB_POOL_MIN=2
DB_POOL_MAX=10
SESSION_COOKIE_SECURE=0
EOF
chmod 600 "$ENV_FILE"
chown "$(stat -c '%U:%G' "$SCRIPT_DIR")" "$ENV_FILE" 2>/dev/null || true

echo
green "==> Done. Summary:"
echo    "    Database  : $DB_NAME"
echo    "    App role  : $DB_USER  (password written to .env)"
echo    "    Superadmin: created (you chose the credentials above)"
echo    "    .env      : regenerated with a strong secret key + app password"
echo
yellow "Next step: activate the venv, install deps, and run the app:"
echo    "    source venv/bin/activate"
echo    "    pip install -r requirements.txt"
echo    "    python app.py   ->  http://127.0.0.1:5000"
echo
yellow "Log in as superadmin at: http://127.0.0.1:5000/superadmin/login"
